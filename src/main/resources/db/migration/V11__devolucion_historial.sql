CREATE TABLE devolucion_historial (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    devolucion_id BIGINT NOT NULL REFERENCES devoluciones(id),
    estado_anterior VARCHAR(20),
    estado_nuevo VARCHAR(20) NOT NULL CHECK (estado_nuevo IN ('SOLICITADA','EN_REVISION','APROBADA','RECHAZADA','COMPLETADA')),
    actor_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    actor_nombre VARCHAR(140) NOT NULL,
    actor_rol VARCHAR(20) NOT NULL,
    observacion VARCHAR(1000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX devolucion_historial_devolucion_fecha_idx ON devolucion_historial(devolucion_id, created_at, id);
CREATE INDEX devolucion_historial_actor_idx ON devolucion_historial(actor_id);
